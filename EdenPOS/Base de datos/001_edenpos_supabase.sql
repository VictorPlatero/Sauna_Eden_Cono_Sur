begin;

create schema edenpos;
revoke all on schema edenpos from public, anon, authenticated;

create table edenpos.settings (
    singleton boolean primary key default true check (singleton),
    store_name text not null,
    currency_symbol text not null default 'S/',
    dni_lookup_enabled boolean not null default false
);

create table edenpos.products (
    id text primary key default gen_random_uuid()::text,
    name text not null,
    category text not null,
    price numeric(14,2) not null check (price >= 0),
    image_file text,
    color_hex text,
    active boolean not null default true,
    track_inventory boolean not null default false,
    stock integer not null default 0 check (stock >= 0),
    initial_stock integer not null default 0 check (initial_stock >= 0)
);

create table edenpos.product_options (
    product_id text references edenpos.products,
    id text default gen_random_uuid()::text,
    name text not null,
    price numeric(14,2) not null check (price >= 0),
    track_inventory boolean not null default false,
    stock integer not null default 0 check (stock >= 0),
    initial_stock integer not null default 0 check (initial_stock >= 0),
    primary key (product_id, id)
);

create table edenpos.customers (
    dni text primary key check (dni ~ '^[0-9]{8}$'),
    full_name text not null,
    source text,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table edenpos.shifts (
    id text primary key default gen_random_uuid()::text,
    number bigint generated by default as identity unique,
    employee text not null,
    opened_at timestamptz not null default now(),
    closed_at timestamptz check (closed_at >= opened_at),
    opening_amount numeric(14,2) not null check (opening_amount >= 0),
    closing_amount numeric(14,2) check (closing_amount >= 0),
    expected_amount numeric(14,2),
    is_open boolean generated always as (closed_at is null) stored
);

create unique index shifts_one_open on edenpos.shifts (is_open) where is_open;

create table edenpos.cash_movements (
    id text primary key default gen_random_uuid()::text,
    shift_id text not null references edenpos.shifts,
    created_at timestamptz not null default now(),
    employee text not null,
    type text not null,
    amount numeric(14,2) not null check (amount <> 0),
    comment text
);

create table edenpos.receipts (
    id text primary key default gen_random_uuid()::text,
    number bigint generated by default as identity unique,
    shift_id text references edenpos.shifts,
    created_at timestamptz not null default now(),
    employee text not null,
    customer_name text,
    customer_dni text check (customer_dni ~ '^[0-9]{8}$'),
    payment_method text not null check (payment_method in ('Efectivo', 'Yape', 'Mixto')),
    amount_received numeric(14,2) not null default 0 check (amount_received >= 0),
    cash_amount numeric(14,2) not null default 0 check (cash_amount >= 0),
    yape_amount numeric(14,2) not null default 0 check (yape_amount >= 0),
    total numeric(14,2) not null check (total >= 0),
    status text not null check (status in ('Pagado', 'Reembolsado')),
    refunded_at timestamptz check (refunded_at >= created_at),
    refund_reason text
);

create table edenpos.receipt_lines (
    receipt_id text references edenpos.receipts,
    line_number integer check (line_number > 0),
    product_id text,
    option_id text,
    name text not null,
    comment text,
    unit_price numeric(14,2) not null check (unit_price >= 0),
    quantity integer not null check (quantity > 0),
    line_total numeric(18,2) generated always as (unit_price * quantity) stored,
    primary key (receipt_id, line_number)
);

create table edenpos.saved_tickets (
    id text primary key default gen_random_uuid()::text,
    name text not null,
    customer_name text,
    customer_dni text check (customer_dni ~ '^[0-9]{8}$'),
    adult_count integer not null default 0 check (adult_count >= 0),
    child_count integer not null default 0 check (child_count >= 0),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table edenpos.saved_ticket_lockers (
    ticket_id text not null references edenpos.saved_tickets on delete cascade,
    locker_number integer primary key check (locker_number between 1 and 35)
);

create table edenpos.saved_ticket_lines (
    ticket_id text references edenpos.saved_tickets on delete cascade,
    line_number integer check (line_number > 0),
    product_id text,
    option_id text,
    name text not null,
    comment text,
    unit_price numeric(14,2) not null check (unit_price >= 0),
    quantity integer not null check (quantity > 0),
    line_total numeric(18,2) generated always as (unit_price * quantity) stored,
    primary key (ticket_id, line_number)
);

create table edenpos.inventory_movements (
    id text primary key default gen_random_uuid()::text,
    product_id text not null,
    option_id text,
    product_name text not null,
    created_at timestamptz not null default now(),
    type text not null,
    quantity integer not null,
    previous_stock integer not null check (previous_stock >= 0),
    new_stock integer not null check (new_stock >= 0),
    note text,
    reference_id text
);

-- Historical lines and inventory movements retain identifiers and names
-- even when a product or variation is removed from the catalog.
create index products_active_category on edenpos.products (category, name) where active;
create index receipts_created_at on edenpos.receipts (created_at desc);
create index receipts_shift_created_at on edenpos.receipts (shift_id, created_at);
create index cash_movements_shift_created_at on edenpos.cash_movements (shift_id, created_at);
create index inventory_movements_product_created_at
    on edenpos.inventory_movements (product_id, created_at desc);
create index saved_ticket_lockers_ticket on edenpos.saved_ticket_lockers (ticket_id);

alter table edenpos.settings enable row level security;
alter table edenpos.products enable row level security;
alter table edenpos.product_options enable row level security;
alter table edenpos.customers enable row level security;
alter table edenpos.shifts enable row level security;
alter table edenpos.cash_movements enable row level security;
alter table edenpos.receipts enable row level security;
alter table edenpos.receipt_lines enable row level security;
alter table edenpos.saved_tickets enable row level security;
alter table edenpos.saved_ticket_lockers enable row level security;
alter table edenpos.saved_ticket_lines enable row level security;
alter table edenpos.inventory_movements enable row level security;

revoke all on all tables in schema edenpos from public, anon, authenticated;
revoke all on all sequences in schema edenpos from public, anon, authenticated;

commit;
